// Bundles scripts/board-cli.ts and the pure modules it uses into one plain JavaScript file,
// kept as a string in hooks/board-script.ts for `/progress connect` to write out. Run with
// Bun after changing any of them: `bun scripts/build-board.ts`. `--check` fails when the
// kept copy is out of date (CI runs it).
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { RELEASED } from '../hooks/released'

const root = join(import.meta.dir, '..')
const version: string = JSON.parse(readFileSync(join(root, '.claude-plugin', 'plugin.json'), 'utf8')).version
// The native setup worker imports released ownership. Its bundle cannot contain
// its own fingerprint: updating that table would otherwise change the hash again.
// Keep historical boards and all command/reporter hashes; exact current output
// is recognized by the installer before historical ownership is consulted.
const bundled = RELEASED.map(release => release.version === version ? { ...release, board: [] } : release)
const built = await Bun.build({
  entrypoints: [join(root, 'scripts', 'board-cli.ts')], target: 'node', format: 'esm',
  plugins: [{
    name: 'released-board-ownership',
    setup(build) {
      build.onLoad({ filter: /[\\/]hooks[\\/]released\.ts$/ }, ({ path }) => {
        if (path !== join(root, 'hooks', 'released.ts')) return
        return { contents: `export const RELEASED = ${JSON.stringify(bundled)}`, loader: 'js' }
      })
    },
  }],
})
if (!built.success) throw new AggregateError(built.logs, 'bundling the board failed')
const code = await built.outputs[0]!.text()
const out = `// Generated by scripts/build-board.ts from scripts/board-cli.ts; do not edit by hand.\nexport const BOARD_SCRIPT = ${JSON.stringify(code)}\n`
const target = join(root, 'hooks', 'board-script.ts')

if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== out) {
    console.error('hooks/board-script.ts is out of date: run `bun scripts/build-board.ts`')
    process.exit(1)
  }
} else {
  writeFileSync(target, out)
  console.log(`wrote hooks/board-script.ts (${code.length} characters)`)
}
